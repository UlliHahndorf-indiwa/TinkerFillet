// Generates the STL files used to try the application by hand.
//
// The same shapes the unit tests use, written out as real files so the whole
// path - file input, reader, reconstruction, kernel, viewport - can be walked
// the way a user walks it.
//
// Run: node tools/make-test-stl.mjs [outputDirectory]

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = process.argv[2] ?? "src/TinkerFillet.App/wwwroot/dev";
mkdirSync(out, { recursive: true });

const add = (list, a, b, c) => list.push([...a, ...b, ...c]);
const quad = (list, a, b, c, d) => {
  add(list, a, b, c);
  add(list, a, c, d);
};
const lerp = (origin, u, v, s, t) => [
  origin[0] + u[0] * s + v[0] * t,
  origin[1] + u[1] * s + v[1] * t,
  origin[2] + u[2] * s + v[2] * t,
];

/** Cube with each face split into a grid, the way a CAD exporter emits one. */
function cube(size = 20, subdivisions = 4) {
  const faces = [
    [[0, 0, 0], [0, size, 0], [size, 0, 0]],
    [[0, 0, size], [size, 0, 0], [0, size, 0]],
    [[0, 0, 0], [size, 0, 0], [0, 0, size]],
    [[0, size, 0], [0, 0, size], [size, 0, 0]],
    [[0, 0, 0], [0, 0, size], [0, size, 0]],
    [[size, 0, 0], [0, size, 0], [0, 0, size]],
  ];

  const triangles = [];
  for (const [origin, u, v] of faces) {
    for (let i = 0; i < subdivisions; i++) {
      for (let j = 0; j < subdivisions; j++) {
        const [s0, s1] = [i / subdivisions, (i + 1) / subdivisions];
        const [t0, t1] = [j / subdivisions, (j + 1) / subdivisions];
        quad(triangles,
          lerp(origin, u, v, s0, t0), lerp(origin, u, v, s1, t0),
          lerp(origin, u, v, s1, t1), lerp(origin, u, v, s0, t1));
      }
    }
  }
  return triangles;
}

/** Plate with a square hole, everything cut from one grid so it stays manifold. */
function plateWithHole(w = 40, d = 40, t = 6, hole = 12) {
  const xs = [0, (w - hole) / 2, (w + hole) / 2, w];
  const ys = [0, (d - hole) / 2, (d + hole) / 2, d];
  const triangles = [];

  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
      if (i === 1 && j === 1) continue;
      quad(triangles, [xs[i], ys[j], t], [xs[i + 1], ys[j], t], [xs[i + 1], ys[j + 1], t], [xs[i], ys[j + 1], t]);
      quad(triangles, [xs[i], ys[j], 0], [xs[i], ys[j + 1], 0], [xs[i + 1], ys[j + 1], 0], [xs[i + 1], ys[j], 0]);
    }
  }

  for (let i = 0; i < 3; i++) {
    quad(triangles, [xs[i], 0, 0], [xs[i + 1], 0, 0], [xs[i + 1], 0, t], [xs[i], 0, t]);
    quad(triangles, [xs[i + 1], d, 0], [xs[i], d, 0], [xs[i], d, t], [xs[i + 1], d, t]);
  }
  for (let j = 0; j < 3; j++) {
    quad(triangles, [w, ys[j], 0], [w, ys[j + 1], 0], [w, ys[j + 1], t], [w, ys[j], t]);
    quad(triangles, [0, ys[j + 1], 0], [0, ys[j], 0], [0, ys[j], t], [0, ys[j + 1], t]);
  }

  quad(triangles, [xs[1], ys[1], 0], [xs[1], ys[1], t], [xs[2], ys[1], t], [xs[2], ys[1], 0]);
  quad(triangles, [xs[2], ys[1], 0], [xs[2], ys[1], t], [xs[2], ys[2], t], [xs[2], ys[2], 0]);
  quad(triangles, [xs[2], ys[2], 0], [xs[2], ys[2], t], [xs[1], ys[2], t], [xs[1], ys[2], 0]);
  quad(triangles, [xs[1], ys[2], 0], [xs[1], ys[2], t], [xs[1], ys[1], t], [xs[1], ys[1], 0]);

  return triangles;
}

/** Tessellated cylinder: a rim of many short segments, the case chains exist for. */
function prism(sides = 20, radius = 12, height = 25) {
  const ring = Array.from({ length: sides }, (_, i) => {
    const angle = (2 * Math.PI * i) / sides;
    return [radius * Math.cos(angle), radius * Math.sin(angle), 0];
  });

  const triangles = [];
  for (let i = 0; i < sides; i++) {
    const a = ring[i];
    const b = ring[(i + 1) % sides];
    const aTop = [a[0], a[1], height];
    const bTop = [b[0], b[1], height];
    quad(triangles, a, b, bTop, aTop);
    add(triangles, [0, 0, 0], b, a);
    add(triangles, [0, 0, height], aTop, bTop);
  }
  return triangles;
}

function writeBinaryStl(path, triangles) {
  const bytes = Buffer.alloc(84 + triangles.length * 50);
  bytes.write("generated by tools/make-test-stl.mjs", 0, "ascii");
  bytes.writeUInt32LE(triangles.length, 80);

  triangles.forEach((triangle, index) => {
    let at = 84 + index * 50;
    at += 12; // facet normal left at zero: the reader recomputes it anyway
    for (const value of triangle) {
      bytes.writeFloatLE(value, at);
      at += 4;
    }
  });

  writeFileSync(path, bytes);
  console.log(`${path}: ${triangles.length} triangles`);
}

writeBinaryStl(join(out, "cube.stl"), cube());
writeBinaryStl(join(out, "plate-with-hole.stl"), plateWithHole());
writeBinaryStl(join(out, "prism-20.stl"), prism());

/** Washer: a convex outer cylinder and a concave bore, both tessellated. */
function washer(sides = 24, outerRadius = 20, holeRadius = 8, thickness = 6) {
  const on = (r, i, z) => {
    const a = (2 * Math.PI * i) / sides;
    return [r * Math.cos(a), r * Math.sin(a), z];
  };
  const triangles = [];
  for (let i = 0; i < sides; i++) {
    const j = (i + 1) % sides;
    quad(triangles, on(holeRadius, i, thickness), on(outerRadius, i, thickness),
      on(outerRadius, j, thickness), on(holeRadius, j, thickness));
    quad(triangles, on(holeRadius, i, 0), on(holeRadius, j, 0),
      on(outerRadius, j, 0), on(outerRadius, i, 0));
    quad(triangles, on(outerRadius, i, 0), on(outerRadius, j, 0),
      on(outerRadius, j, thickness), on(outerRadius, i, thickness));
    quad(triangles, on(holeRadius, i, 0), on(holeRadius, i, thickness),
      on(holeRadius, j, thickness), on(holeRadius, j, 0));
  }
  return triangles;
}

writeBinaryStl(join(out, "washer.stl"), washer());

/** Tessellated cone and truncated cone: fans whose side edges converge. */
function coneShape(sides = 24, bottomRadius = 12, topRadius = 0, height = 18) {
  const on = (r, i, z) => {
    const a = (2 * Math.PI * i) / sides;
    return [r * Math.cos(a), r * Math.sin(a), z];
  };
  const triangles = [];
  for (let i = 0; i < sides; i++) {
    const j = (i + 1) % sides;
    if (topRadius <= 0) {
      add(triangles, on(bottomRadius, i, 0), on(bottomRadius, j, 0), [0, 0, height]);
    } else {
      quad(triangles, on(bottomRadius, i, 0), on(bottomRadius, j, 0),
        on(topRadius, j, height), on(topRadius, i, height));
      add(triangles, [0, 0, height], on(topRadius, i, height), on(topRadius, j, height));
    }
    add(triangles, [0, 0, 0], on(bottomRadius, j, 0), on(bottomRadius, i, 0));
  }
  return triangles;
}

writeBinaryStl(join(out, "cone.stl"), coneShape());
writeBinaryStl(join(out, "cone-truncated.stl"), coneShape(24, 14, 6, 15));
